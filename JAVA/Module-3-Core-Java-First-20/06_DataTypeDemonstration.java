class DataTypeDemonstration {
    public static void main(String[] args) {
        int age = 20;
        float percentage = 85.5f;
        double marks = 92.75;
        char grade = 'A';
        boolean passed = true;

        System.out.println("int value: " + age);
        System.out.println("float value: " + percentage);
        System.out.println("double value: " + marks);
        System.out.println("char value: " + grade);
        System.out.println("boolean value: " + passed);
    }
}

